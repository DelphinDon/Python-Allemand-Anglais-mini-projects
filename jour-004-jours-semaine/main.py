# --- Version allemande ---
jours_de = ["Montag", "Dienstag", "Mittwoch", "Donnerstag", "Freitag", "Samstag", "Sonntag"]

print("Die Wochentage auf Deutsch sind: ")
for jour in jours_de:
    print(f"- {jour}")
    

