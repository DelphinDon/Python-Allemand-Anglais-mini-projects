# --- Version allemand ---
wort = input("Gib ein deutsches Wort ein: ")

if "a" in wort:
    print(f"Das Wort '{wort}' enthält den Buchstaben 'a'.")
else:
    print(f"Das Wort '{wort}' enthält nicht den Buchstaben 'a'.")
    
# --- Version anglaise ---
word = input("\nEnter an English word: ")
if "a" in word:
    print(f"The word '{word}' contains the letter 'a'.")
else:
    print(f"The word '{word}' does not contain the letter 'a'.")