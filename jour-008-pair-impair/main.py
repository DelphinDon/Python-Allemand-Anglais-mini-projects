# --- Version allemande ---
zahl = int(input("Gib eine Zahl ein: "))

if zahl % 2 == 0:
    print(f"{zahl} ist gerade.")
else:
    print(f"{zahl} ist ungerade.")
    

# --- Version anglaise ---
number = int(input("\nEnter a number: "))
if number % 2 == 0:
    print(f"{number} is even.")
else:
    print(f"{number} is odd.")